// The copy-upgrade plan upgrades a COPY of the data volume.
//
// It exists because for RabbitMQ there is no logical dump that reproduces a
// node — export_definitions carries no MESSAGES, and the vendor's only
// supported restore is a byte copy of a STOPPED node's data directory onto a
// node with exactly the same name — so "dump it out and replay it in" is not
// available. What is available is: copy the volume, upgrade the copy, and
// leave the original untouched.
//
// That last part is the whole safety story, and it is structural rather than a
// rule to remember. Inside the RUN the source volume is derived once and
// journalled — so the verdict can tell the operator which volume they may now
// reclaim — and from there it is touched by exactly one step: the copy, which
// hands it to Env.CopyVolume mounted read-only. (CopyPreflight names it too,
// but only to check that it exists and to measure it.) Every container the
// plan runs is generated by
// tempDef, which forces the TARGET generation — so no container can land on
// the source even by accident, and the rollback stays "delete the volume we
// made".

// CopySpec is everything the shared copy-upgrade plan does not know about a
// dependency. Every hook runs against a temp container on the COPY; none of
// them may name the source volume.
type CopySpec struct {
	ID deps.ID
	// TempEnv is extra environment for both temp containers, and HostAlias
	// extra /etc/hosts entries. Together they are how a dependency whose
	// identity is derived from its hostname (RabbitMQ's rabbit@$HOSTNAME, and
	// the data path that contains it) keeps that identity under a temp
	// container's override name. Both halves or neither: see
	// deps.TempContainerOpts.
	TempEnv   map[string]string
	HostAlias map[string]string
	// WaitReady blocks until the dependency in container really answers.
	// Required — "the container is running" is not readiness for any of these
	// (a RabbitMQ node answers `ping` long before it has booted).
	WaitReady func(ctx context.Context, env Env, container string, p StepProgress) error
	// PreUpgrade runs on the OLD image on the copy, PostUpgrade on the NEW
	// one. Either may be nil. For RabbitMQ they are the two halves of one
	// decision: the pre-step enables the feature flags a new node refuses to
	// start without, the post-step delivers what the upgrade was done for.
	PreUpgrade  func(ctx context.Context, env Env, container string, p StepProgress) error
	PostUpgrade func(ctx context.Context, env Env, container string, p StepProgress) error
	// Inventory is the dependency's "before"/"after" picture, captured on the
	// old node and compared on the new one. Required: a verify step that
	// verifies nothing would be a lie told on the operator's progress screen.
	Inventory func(ctx context.Context, env Env, container string) (Inventory, error)
	// EnsureDirs are directories the copy must contain before a container is
	// started on it, relative to the volume root. A temp container runs the
	// CONTAINER and nothing around it — no init actions, no probes and no INIT
	// CONTAINERS — and ZooKeeper's generated def has an init container whose
	// only job is to make its data directories. A faithful copy of a volume
	// that has ever run already has them, so this covers exactly the
	// empty-source case a preflight warns about.
	EnsureDirs []string
}

// Inventory is a dependency's picture of its own data. Diff returns the
// differences that FAIL the verify (empty = the data survived) and, separately,
// the ones that are merely reported.
//
// The split is not tidiness: ZooKeeper's ephemeral nodes belong to client
// sessions, the copy is booted with no clients, and their sessions expire
// while the migration runs — so a comparison that treated every difference as
// a failure would fail every real migration, while one that treated none as a
// failure would not notice a lost patch-result marker.
type Inventory interface {
	Diff(after Inventory) (problems []string, notes []string)
}

// CopyVolumes names the two volumes a copy upgrade moves between and the
// generation the commit will pin.
type CopyVolumes struct {
	Source    string
	Target    string
	TargetGen int
}

// CopyStepIDs are the ids of the copy-upgrade plan's steps, in order. It is
// exported for the same reason PostgresStepIDs is: the CLI's locale keys, the
// web dialog's step list and the tests all name this list, and a step renamed
// in the plan without them is a progress screen full of raw ids.
//
// The ids deliberately do NOT reuse the PostgreSQL plan's "start-source" /
// "start-target". They are locale keys, and a container running the old image
// on a COPY is not "the current database": describing it that way would tell
// the operator their live data is being started up and written to, which is
// precisely what this plan does not do.
func CopyStepIDs() []string {
	return []string{
		"stop-namespace", "pull-image", "create-volume", "copy-volume",
		"start-old", "pre-upgrade", "stop-old", "start-new", "post-upgrade",
		"verify", "stop-new",
	}
}

// CopyPreflight runs the half of a copy-upgrade preflight that is the same for
// every dependency: the shared version checks, the migrator's own pair rule,
// the source volume's existence, the space one more copy needs, and an
// existing target volume.
//
// ok=false means it refused and the caller must return res as it stands — the
// volumes are not named, and nothing dependency-specific should be probed
// against a pair that is not going to happen. ok=true means the caller may
// append its own problems and warnings and then set res.OK itself.
func CopyPreflight(
	ctx context.Context, env Env, id deps.ID, path Path,
	supportsPair func(from, to deps.Version) (ok bool, problem msg.Message),
) (PreflightResult, CopyVolumes, bool) {
	res := NewPreflightResult(path.From(), path.To())
	res.WasRunning = env.IsRunning()
	// The ends decide whether a migration is needed at all (a downgrade, an
	// unparsable tag, a pair that needs no migration); the HOPS decide whether
	// the route can be walked. Both, in that order.
	if _, _, problems := versionProblems(id, path.From(), path.To()); len(problems) > 0 {
		res.Problems = append(res.Problems, problems...)
		return res, CopyVolumes{}, false
	}
	d, ok := deps.Lookup(id)
	if !ok { // unreachable: versionProblems just looked it up
		res.Problems = append(res.Problems, NotRegisteredProblem(id))
		return res, CopyVolumes{}, false
	}
	for _, hop := range path.Hops() {
		fromV, okFrom := d.ParseVersion(hop[0])
		toV, okTo := d.ParseVersion(hop[1])
		switch {
		case !okFrom:
			res.Problems = append(res.Problems, msg.New("deps.msg.version.unreadableFrom", "image", hop[0]))
			return res, CopyVolumes{}, false
		case !okTo:
			res.Problems = append(res.Problems, msg.New("deps.msg.version.unreadableTo", "image", hop[1]))
			return res, CopyVolumes{}, false
		}
		if ok, problem := supportsPair(fromV, toV); !ok {
			res.Problems = append(res.Problems, pairRefusal(problem, hop[0], hop[1]))
			return res, CopyVolumes{}, false
		}
	}
	src, dst, toGen := migrationVolumes(d, env.DependencyState(id))
	vols := CopyVolumes{Source: src, Target: dst, TargetGen: toGen}

	// The source volume's existence is a PROBLEM and not a warning: the pin
	// says the namespace has data on this version, and a plan that ran without
	// it would copy nothing, boot an empty node on the copy, verify it against
	// an equally empty "before" picture and commit that as the migration.
	exists, err := env.VolumeExists(ctx, src)
	switch {
	case err != nil:
		res.Problems = append(res.Problems, VolumeCheckProblem(src, err))
		return res, vols, false
	case !exists:
		res.Problems = append(res.Problems,
			msg.New("deps.msg.volume.sourceMissing", "volume", src, "id", string(id)))
		return res, vols, false
	}
	res.copySpace(ctx, env, src)
	// "" — neither RabbitMQ nor ZooKeeper writes a version marker into its
	// data, and inventing one would tell the operator the leftover volume
	// holds a version it never claimed.
	res.checkExistingTarget(ctx, env, dst, "")
	return res, vols, true
}

// copyRun is the state one copy-upgrade run carries between its steps. The
// engine runs steps sequentially on one goroutine, which is what makes the
// hand-off of the "before" inventory safe.
type copyRun struct {
	env  Env
	spec CopySpec
	// path is the whole route. path.From() is the image the copy is first
	// started under; every rung after it (path.Rungs()) is a version the copy
	// is raised through, in order. dstVolume is the copy, and it is the ONLY
	// volume any container of this plan is generated for (see tempDef).
	path      Path
	opts      PlanOptions
	toGen     int
	dstVolume string
	// srcVolume is used in exactly one place — the copy step — and mounted
	// read-only there. Nothing else in this type may name it.
	srcVolume string
	dataSize  int64

	before Inventory
}

// BuildCopyUpgrade turns a dependency's CopySpec into the shared plan.
//
// pre is the migrator's OWN preflight result (which starts from CopyPreflight
// above): the two refusals every copy migrator shares — a preflight that
// failed, and an existing target volume the user has not agreed to replace —
// live here so three migrators cannot word them three ways.
func BuildCopyUpgrade(env Env, spec CopySpec, path Path, opts PlanOptions, pre PreflightResult) (*Plan, deps.MigrationJournal, error) {
	from, to := path.From(), path.To()
	if err := spec.validate(); err != nil {
		return nil, deps.MigrationJournal{}, err
	}
	if !pre.OK {
		return nil, deps.MigrationJournal{}, refusePlan(pre.Problems...)
	}
	if pre.ExistingTargetVolume != nil && !opts.ReplaceExistingVolume {
		return nil, deps.MigrationJournal{}, refusePlan(existingVolumeRefusal(pre.ExistingTargetVolume.Name))
	}
	d, ok := deps.Lookup(spec.ID)
	if !ok {
		return nil, deps.MigrationJournal{}, refusePlan(NotRegisteredProblem(spec.ID))
	}
	// The pin is read ONCE, and the journal carries what was derived from it,
	// so nothing later has to re-derive a generation from a world the
	// migration is rewriting.
	src, dst, toGen := migrationVolumes(d, env.DependencyState(spec.ID))
	r := &copyRun{
		env: env, spec: spec, path: path, opts: opts,
		toGen: toGen, dstVolume: dst, srcVolume: src, dataSize: pre.DataSizeBytes,
	}
	j := deps.MigrationJournal{
		ID: spec.ID, From: from, To: to,
		ToVolumeGen: toGen, SourceVolume: src,
		WasRunning: env.IsRunning(),
		StartedAt:  time.Now(),
	}
	steps := []Step{
		{ID: "stop-namespace", Run: r.stopNamespace},
		{ID: "pull-image", Run: r.pullImages},
		{ID: "create-volume", Run: r.createVolume},
		{ID: "copy-volume", Run: r.copyVolume},
		{ID: "start-old", Run: r.startOld},
	}
	// Every rung after the bottom is climbed by the same four-step shape:
	// prepare the node that is about to be replaced, stop it, start the rung,
	// let the new node finish settling in. pre-upgrade runs on EVERY rung
	// (there is always a node below it to prepare, and on the first rung that
	// node also yields the "before" inventory); verify and the final
	// stop-new run only once, after the LAST rung, because that is the only
	// point with nothing left to climb to.
	rungs := path.Rungs()
	for i, rung := range rungs {
		last := i == len(rungs)-1
		steps = append(steps,
			Step{ID: "pre-upgrade", Run: r.preUpgradeAt(i)},
			Step{ID: stopIDFor(i), Run: r.stopCurrent(i)},
			Step{ID: "start-new", Run: r.startRung(rung)},
			Step{ID: "post-upgrade", Run: r.postUpgrade},
		)
		if last {
			steps = append(steps,
				Step{ID: "verify", Run: r.verify},
				Step{ID: "stop-new", Run: r.stopNew},
			)
		}
	}
	plan := &Plan{
		Diagnose: tempContainerDiagnostics(env),
		Steps:    steps,
		Rollback: func(ctx context.Context, j *deps.MigrationJournal) error {
			return RollbackCopyUpgrade(ctx, env, j)
		},
		// Only OldVolume, read from the JOURNAL: the engine fills the identity
		// (id, from, to) from there too, and it is the single source of truth
		// for what moved where.
		Result: func(j *deps.MigrationJournal) deps.MigrationResult {
			return deps.MigrationResult{OldVolume: j.SourceVolume}
		},
		Finalize: r.finalize,
	}
	return plan, j, nil
}

// validate refuses a spec whose missing piece would show up as a silently
// weaker migration rather than as an error: no readiness probe means every
// step racing a booting server, and no inventory means a verify step that
// verifies nothing.
func (s CopySpec) validate() error {
	switch {
	case s.ID == "":
		return errors.New("copy-upgrade spec has no dependency id")
	case s.WaitReady == nil:
		return fmt.Errorf("copy-upgrade spec for %s has no readiness probe", s.ID)
	case s.Inventory == nil:
		return fmt.Errorf("copy-upgrade spec for %s has no inventory", s.ID)
	}
	return nil
}

func (r *copyRun) stopNamespace(ctx context.Context, _ *Journal, _ StepProgress) error {
	return stopNamespaceStep(ctx, r.env)
}

// pullImages pulls EVERY rung before anything irreversible happens. An
// unreachable registry then costs a stopped namespace and nothing else — and
// on a ladder that has to hold for the rung four steps up, not just the
// first.
func (r *copyRun) pullImages(ctx context.Context, _ *Journal, p StepProgress) error {
	for _, image := range r.path.Rungs() {
		if err := pullImageStep(ctx, r.env, image, p); err != nil {
			return err
		}
	}
	return nil
}

// createVolume makes the volume this plan writes into; the write-ahead
// discipline and the refusal of a volume that appeared after the preflight are
// shared with the other plan (createTargetVolume).
func (r *copyRun) createVolume(ctx context.Context, j *Journal, _ StepProgress) error {
	return createTargetVolume(ctx, r.env, j, r.dstVolume, r.opts.ReplaceExistingVolume)
}

// copyVolume is the ONE place in this plan that names the source volume, and
// Env.CopyVolume mounts it read-only. Everything after this point works on the
// copy alone.
//
// It reports indeterminate progress on purpose: sampling the destination's
// size for a percentage would spawn one helper container per sample on a
// desktop, and both renderers already draw percent 0 as indeterminate.
func (r *copyRun) copyVolume(ctx context.Context, _ *Journal, p StepProgress) error {
	p(0, msg.New("deps.msg.progress.copying", "size", fsutil.FormatBytes(r.dataSize)))
	if err := r.env.CopyVolume(ctx, r.srcVolume, r.dstVolume); err != nil {
		return fmt.Errorf("copy %s to %s: %w", r.srcVolume, r.dstVolume, err)
	}
	if len(r.spec.EnsureDirs) > 0 {
		if err := r.env.EnsureVolumeDirs(ctx, r.dstVolume, r.spec.EnsureDirs); err != nil {
			return fmt.Errorf("create %s in %s: %w", strings.Join(r.spec.EnsureDirs, ", "), r.dstVolume, err)
		}
	}
	return nil
}

func (r *copyRun) startOld(ctx context.Context, _ *Journal, p StepProgress) error {
	return r.startTemp(ctx, r.path.From(), SrcContainer, p)
}

// startRung starts the temp container for one rung of the ladder. It always
// lands on DstContainer: after the first rung, the bottom node's name
// (SrcContainer) is retired for the whole rest of the climb, and every later
// "current" node — one started by a previous iteration of this same method —
// is also DstContainer.
func (r *copyRun) startRung(image string) func(context.Context, *Journal, StepProgress) error {
	return func(ctx context.Context, _ *Journal, p StepProgress) error {
		return r.startTemp(ctx, image, DstContainer, p)
	}
}

// startTemp runs one temp container on the COPY, under a name of its own and
// with the dependency's node identity pinned. It opens its step by naming the
// image, so a repeated "start-new" (one per rung) says which rung it is.
func (r *copyRun) startTemp(ctx context.Context, image, name string, p StepProgress) error {
	p(0, msg.New("deps.msg.progress.starting", "image", image))
	def, err := r.tempDef(image)
	if err != nil {
		return err
	}
	if _, err := r.env.RunAppDef(ctx, def, deps.TempContainerOpts{
		Name: name, Env: r.spec.TempEnv, HostAlias: r.spec.HostAlias,
	}); err != nil {
		return fmt.Errorf("start %s: %w", name, err)
	}
	return r.spec.WaitReady(ctx, r.env, name, p)
}

// tempDef is the ONE place a container of this plan learns which volume it
// mounts, and it always answers the COPY.
//
// That is what makes "the original is only ever read" structural: there is no
// second call to GenerateDefFor in this file, so a future step cannot mount
// the source by passing the wrong generation — it has no generation to pass.
func (r *copyRun) tempDef(image string) (appdef.ApplicationDef, error) {
	def, err := r.env.GenerateDefFor(r.spec.ID, deps.DependencyState{Image: image, VolumeGen: r.toGen})
	if err != nil {
		return appdef.ApplicationDef{}, fmt.Errorf("generate the %s definition: %w", image, err)
	}
	return def, nil
}

// stopIDFor names the step that stops the node BELOW rung i, the one about to
// be replaced. The first one is the OLD image, started by startOld under
// SrcContainer, and keeps the plan's existing "stop-old" key; every later one
// is an intermediate rung the plan itself started under DstContainer (see
// startRung), which is "stop-new" — the same id the plan's final cleanup step
// uses, since both stop a node the plan itself started under that name.
func stopIDFor(i int) string {
	if i == 0 {
		return "stop-old"
	}
	return "stop-new"
}

// preUpgradeAt runs the dependency's own pre-upgrade work on the node that is
// running now — the one about to be replaced by rung i — and, on the FIRST
// rung only, captures the "before" inventory.
//
// It runs before EVERY rung, not just the first: pre-upgrade prepares the
// node that is about to be REPLACED for what comes next (RabbitMQ's feature
// flags a new node refuses to start without), so a 4.1 → 4.2 → 4.3 ladder
// needs it once on 4.1 and once on 4.2, each against the then-current image.
// After the top rung there is no next node to prepare, and the loop simply
// has no further iteration to run it in.
//
// The inventory is taken HERE, from the copy, and only on the first rung —
// from the bottom of the ladder — because that is what the verify at the top
// compares against. An intermediate comparison would measure work a rung
// legitimately did to the data, the same reason Qdrant's own inventory
// deliberately ignores status and config. Reading it from the namespace's own
// container before it was stopped would also only work when the namespace was
// running, and starting the old image on the ORIGINAL volume to read it is
// exactly what this plan does not do — the copy is the same bytes, and the
// old image has to run on it anyway.
func (r *copyRun) preUpgradeAt(i int) func(context.Context, *Journal, StepProgress) error {
	container := DstContainer
	if i == 0 {
		container = SrcContainer
	}
	return func(ctx context.Context, _ *Journal, p StepProgress) error {
		if r.spec.PreUpgrade != nil {
			if err := r.spec.PreUpgrade(ctx, r.env, container, p); err != nil {
				return fmt.Errorf("pre-upgrade: %w", err)
			}
		}
		if i != 0 {
			return nil
		}
		inv, err := r.spec.Inventory(ctx, r.env, container)
		if err != nil {
			return fmt.Errorf("read the inventory of %s: %w", r.path.From(), err)
		}
		r.before = inv
		return nil
	}
}

func (r *copyRun) postUpgrade(ctx context.Context, _ *Journal, p StepProgress) error {
	if r.spec.PostUpgrade == nil {
		return nil
	}
	if err := r.spec.PostUpgrade(ctx, r.env, DstContainer, p); err != nil {
		return fmt.Errorf("post-upgrade: %w", err)
	}
	return nil
}

// stopCurrent stops the node BELOW rung i — see stopIDFor for which container
// that is.
func (r *copyRun) stopCurrent(i int) func(context.Context, *Journal, StepProgress) error {
	container := DstContainer
	if i == 0 {
		container = SrcContainer
	}
	return func(ctx context.Context, _ *Journal, _ StepProgress) error {
		if err := r.env.StopRemove(ctx, container); err != nil {
			return fmt.Errorf("remove %s: %w", container, err)
		}
		return nil
	}
}

func (r *copyRun) stopNew(ctx context.Context, _ *Journal, _ StepProgress) error {
	if err := r.env.StopRemove(ctx, DstContainer); err != nil {
		return fmt.Errorf("remove %s: %w", DstContainer, err)
	}
	return nil
}

// verify compares the two live inventories. Problems fail the step — and with
// it the whole migration, which rolls back to the untouched original — while
// notes are reported and nothing more.
func (r *copyRun) verify(ctx context.Context, _ *Journal, p StepProgress) error {
	after, err := r.spec.Inventory(ctx, r.env, DstContainer)
	if err != nil {
		return fmt.Errorf("read the inventory of %s: %w", r.path.To(), err)
	}
	problems, notes := r.before.Diff(after)
	if len(problems) > 0 {
		return errors.New(strings.Join(problems, "; "))
	}
	if len(notes) > 0 {
		slog.Info("Dependency migration verify notes", "dependency", r.spec.ID, "notes", strings.Join(notes, "; "))
		// The notes are the dependency's own inventory diff — ZooKeeper's
		// expired ephemeral nodes, RabbitMQ's per-queue counts — assembled by
		// Inventory.Diff, which has no locale keys and would need one per
		// dependency-specific difference. They pass through untranslated, and
		// passthrough is where that decision is written down.
		p(100, passthrough(strings.Join(notes, "; ")))
	}
	return nil
}

// finalize runs AFTER the commit, so its failures are warnings: the data has
// moved and the pin says so. There is no scratch directory to remove — this
// plan writes no host file at all.
func (r *copyRun) finalize(ctx context.Context, j *deps.MigrationJournal) error {
	if err := r.env.ReloadAndStart(ctx, j.WasRunning); err != nil {
		return fmt.Errorf("reload the namespace: %w", err)
	}
	return nil
}

// RollbackCopyUpgrade undoes whatever the journal says was done, and nothing
// else: the source volume is recorded in the journal but never removed here —
// only CreatedVolume is, and the plan never puts the source there.
//
// Idempotent (every removal treats not-found as success), which is what lets
// the daemon's crash recovery run it against a journal whose work may already
// have been undone. It reports every failure it hit rather than stopping at
// the first: a half-done rollback is what the engine keeps the journal open
// for, and the operator needs to know which halves.
//
// The namespace is handed back RUNNING only when the cleanup left nothing
// behind. This plan's temp containers never mount the namespace's own data
// volume, so the second-server hazard that rule was written for cannot arise
// here — but a leftover temp container still holds the name the next attempt
// needs, and one rule for both plans is worth more than a saved restart.
func RollbackCopyUpgrade(ctx context.Context, env Env, j *deps.MigrationJournal) error {
	var errs []error
	for _, c := range []string{SrcContainer, DstContainer} {
		if err := env.StopRemove(ctx, c); err != nil {
			errs = append(errs, fmt.Errorf("remove %s: %w", c, err))
		}
	}
	if j.CreatedVolume != "" {
		if err := env.RemoveVolume(ctx, j.CreatedVolume); err != nil {
			errs = append(errs, fmt.Errorf("remove volume %s: %w", j.CreatedVolume, err))
		}
	}
	if j.WasRunning {
		switch {
		case len(errs) > 0:
			errs = append(errs, errors.New(
				"namespace left stopped: the rollback could not remove its temp containers"))
		default:
			if err := env.ReloadAndStart(ctx, true); err != nil {
				errs = append(errs, fmt.Errorf("restart namespace: %w", err))
			}
		}
	}
	return errors.Join(errs...)
}
